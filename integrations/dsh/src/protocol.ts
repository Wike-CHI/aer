/**
 * The bridge protocol: the only vocabulary the TypeScript plugin and the Python
 * bridge share.
 *
 * Why a protocol at all, rather than the plugin writing to AER directly: AER is
 * Python and DSH is Node. The boundary has to be explicit, and it has to be one
 * layer *below* `AgentExecutionEnvelope`, so the plugin can be tested without
 * Python and the Python side can be tested without DSH. Everything the plugin
 * learned from DSH crosses this boundary as JSON; nothing AER-specific is
 * decided on the TypeScript side.
 *
 * Framing is one JSON object per line in both directions (round-8.2 section 47).
 *
 * @module @aer/dsh-adapter/protocol
 */

/** Bumped when the shape of {@link BridgeRequest} / {@link BridgeResponse} changes. */
export const AER_BRIDGE_PROTOCOL_VERSION = 1;

/**
 * The operations the plugin may ask the bridge to perform.
 *
 * Deliberately small: a plugin that can call arbitrary AER code has no boundary.
 * Every operation maps to one Runtime API call on the Python side.
 */
export type BridgeOperation =
  /** A DSH session became known. Opens or resumes the AER session mapping. */
  | 'session.begin'
  /**
   * A turn began. Under turn granularity this is what opens the AER run, because a
   * turn is the unit that has an input, a trajectory and an outcome (section 12).
   */
  | 'turn.begin'
  /** One durable DSH event, already normalised. Idempotent by `external_event_id`. */
  | 'event.ingest'
  /** A turn ended with the reason DSH reported. Closes that turn's AER run. */
  | 'turn.end'
  /** The model is about to be called. Returns the context AER wants injected. */
  | 'experience.retrieve'
  /** DSH accepted the injected messages into the step. Records the injection. */
  | 'experience.injected'
  /** Liveness. Also the cheapest way for the probe to prove the bridge is alive. */
  | 'ping'
  /** Ordered shutdown: flush, then exit. */
  | 'shutdown';

/** One request from the plugin to the bridge. */
export interface BridgeRequest {
  readonly protocol: number;
  /** Correlates a response with its request. Generated by the plugin. */
  readonly request_id: string;
  readonly operation: BridgeOperation;
  readonly payload: Record<string, unknown>;
}

/** A structured bridge failure. `code` is stable; `message` is for a human. */
export interface BridgeError {
  readonly code: string;
  readonly message: string;
}

/** One response from the bridge to the plugin. */
export interface BridgeResponse {
  readonly protocol: number;
  readonly request_id: string;
  readonly ok: boolean;
  readonly result?: unknown;
  readonly error?: BridgeError;
}

